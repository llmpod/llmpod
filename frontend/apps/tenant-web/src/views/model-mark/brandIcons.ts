/** 多段文本(名称/key/别名)合并后做小写包含匹配;全部为空返回 null */
function matchBrand(rules: BrandRule[], texts: Array<string | null | undefined>): Component | null {
  const lower = texts.filter(Boolean).join(' ').toLowerCase()
  if (!lower) return null
  return rules.find((rule) => rule.keywords.some((keyword) => lower.includes(keyword)))?.icon ?? null
}

