import { defineComponent, h, type Component } from 'vue'

/** 单个 path 的几何与样式描述 */
interface BrandShape {
  d: string
  fill?: string
  /** fill-rule;部分 logo path 需要 evenodd 才能正确镂空 */
  fillRule?: 'evenodd' | 'nonzero'
  stroke?: string
  strokeWidth?: number
  strokeLinecap?: 'round' | 'butt'
  strokeLinejoin?: 'round' | 'miter'
  /** 黑白系品牌(如 KIMI):浅色模式黑、深色模式白,由全局样式 .brand-icon-dark-aware 控制 */
  darkAware?: boolean
}

/** 单一品牌匹配规则 */
interface BrandRule {
  icon: Component
  /** 小写关键词;名称包含任一即命中 */
  keywords: string[]
}

/** 由 path 描述生成函数式 SVG 组件(尺寸由外层 n-icon 的 1em 规则控制) */
function brandIcon(name: string, viewBox: string, shapes: BrandShape[]): Component {
  return defineComponent({
    name,
    render: () =>
      h(
        'svg',
        { viewBox, xmlns: 'http://www.w3.org/2000/svg' },
        shapes.map((shape) =>
          h('path', {
            d: shape.d,
            ...(shape.darkAware ? { class: 'brand-icon-dark-aware' } : { fill: shape.fill ?? 'none' }),
            ...(shape.fillRule ? { 'fill-rule': shape.fillRule } : {}),
            ...(shape.stroke ? { stroke: shape.stroke } : {}),
            ...(shape.strokeWidth ? { 'stroke-width': shape.strokeWidth } : {}),
            ...(shape.strokeLinecap ? { 'stroke-linecap': shape.strokeLinecap } : {}),
            ...(shape.strokeLinejoin ? { 'stroke-linejoin': shape.strokeLinejoin } : {}),
          }),
        ),
      ),
  })
}

